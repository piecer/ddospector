@pytest.mark.parametrize('fault', ['invalid-utf8', 'truncated-utf8', 'utf8-surrogate',
    'bom', 'utf16', 'truncated-json', 'trailing-document', 'negative-infinity',
    'exponent-number', 'negative-zero-float', 'deep-array', 'large-integer',
    'surrogate-key', 'surrogate-value', 'surrogate-path'])
def test_bounded_malformed_wire_is_sanitized(synthetic, observed_io, fault):
    inputs = arguments(synthetic.value)
    raw = inputs['raw_authority']
    if fault == 'invalid-utf8':
        raw = b'\xff' + raw
    elif fault == 'truncated-utf8':
        raw += b'\xe2\x82'
    elif fault == 'utf8-surrogate':
        raw = raw.replace(b'fixture-site', b'\xed\xa0\x80')
    elif fault == 'bom':
        raw = b'\xef\xbb\xbf' + raw
    elif fault == 'utf16':
        raw = raw.decode().encode('utf-16')
    elif fault == 'truncated-json':
        raw = raw[:-1]
    elif fault == 'trailing-document':
        raw += b'{}'
    elif fault in ('negative-infinity', 'exponent-number', 'negative-zero-float', 'large-integer'):
        replacement = {'negative-infinity': b'-Infinity', 'exponent-number': b'1e0',
                       'negative-zero-float': b'-0.0', 'large-integer': b'9' * 5000}[fault]
        assert raw.count(b'"schema_version":1') == 1
        raw = raw.replace(b'"schema_version":1', b'"schema_version":' + replacement)
    elif fault == 'deep-array':
        site = canonical(synthetic.value['site'])
        assert raw.count(site) == 1
        raw = raw.replace(site, b'[' * 1200 + b'0' + b']' * 1200)
    elif fault == 'surrogate-key':
        raw = raw.replace(b'"scope":', b'"\\ud800":')
    elif fault == 'surrogate-value':
        raw = raw.replace(b'fixture-site', b'\\udfff')
    elif fault == 'surrogate-path':
        synthetic.value['owner']['state_directory'] = '/\ud800'
        raw = _wire_inputs(synthetic.value)['raw_authority']
    assert len(raw) <= 8192
    inputs['raw_authority'] = raw
    _refuse(synthetic, observed_io, inputs, 'INVALID_AUTHORITY')


