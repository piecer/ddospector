@pytest.fixture
def observed_io(monkeypatch):
    """Observe, but never replace, the actual file-descriptor operations."""
    calls = {'attempted': [], 'opened': [], 'closed': []}
    real_open, real_close = session._open, session._close

    def opened(path, flags, *args, **kwargs):
        calls['attempted'].append((path, flags))
        fd = real_open(path, flags, *args, **kwargs)
        info = os.fstat(fd)
        calls['opened'].append((path, flags, fd, (info.st_dev, info.st_ino)))
        return fd

    def closed(fd):
        real_close(fd)
        calls['closed'].append(fd)

    monkeypatch.setattr(session, '_open', opened)
    monkeypatch.setattr(session, '_close', closed)
    return calls


def _admit(case, inputs):
    return session.SessionOwner.admit(case.raw, case.confirmation, str(case.directory), **inputs)


def _refuse(case, calls, inputs, code, *, acquires_root=False):
    """Unexpected successful admission is also cleaned up before failing."""
    owner = None
    try:
        with pytest.raises(session.SessionError) as caught:
            owner = _admit(case, inputs)
        failure = caught.value
        assert failure.code == code
        assert str(failure) == code and repr(failure) == code
        assert failure.__cause__ is None
        assert failure.cleanup_uncertain is False
    finally:
        if owner is not None:
            assert owner.close() is True
    assert list(case.directory.iterdir()) == []
    if acquires_root:
        assert len(calls['attempted']) == 1
        assert len(calls['opened']) == 1
        path, flags, fd, identity = calls['opened'][0]
        assert path == str(case.directory)
        assert flags & os.O_DIRECTORY and not flags & os.O_CREAT
        actual = case.directory.stat(follow_symlinks=False)
        assert identity == (actual.st_dev, actual.st_ino)
        assert calls['closed'] == [fd]
    else:
        assert calls == {'attempted': [], 'opened': [], 'closed': []}


def _accept(case, calls, inputs):
    before = copy.deepcopy(inputs)
    owner = None
    callbacks = []

    def action(permit):
        callbacks.append(permit.attempt)
        permit.checkpoint()

    try:
        owner = _admit(case, inputs)
        assert inputs == before
        snapshot = owner.snapshot()
        assert snapshot['state'] == 'READY' and snapshot['schema_version'] == 2
        assert snapshot['authority_sha256'] == inputs['confirmed_authority_sha256']
        path, flags, root_fd, identity = calls['opened'][0]
        actual = os.fstat(root_fd)
        assert path == str(case.directory) and flags & os.O_DIRECTORY
        assert identity == (actual.st_dev, actual.st_ino)
        assert identity == (case.value['owner']['st_dev'], case.value['owner']['st_ino'])
        assert owner.run_attempt(action) == 1
        final = owner.finish()
        # One callback exhausts a one-attempt profile, not a larger profile.
        expected_state = 'COMPLETED' if case.value['budget']['max_attempts'] == 1 else 'INCOMPLETE'
        assert final['state'] == expected_state and final['code'] is None
        assert final['retired'] is True and final['cleanup_uncertain'] is False
        assert final['callbacks_started'] == final['attempts_completed'] == 1
        assert callbacks == [1]
        records = sorted(case.directory.iterdir())
        assert len(records) == 4
        for record in records:
            data = record.read_bytes()
            value = json.loads(data)
            assert value['schema_version'] == 2
            assert value['authority_sha256'] == inputs['confirmed_authority_sha256']
            assert value['profile_sha256'] == case.confirmation
            assert len(data) <= 4096
            assert b'fixture-site' not in data and b'PRIVATE_SENTINEL' not in data
        assert calls['closed'].count(root_fd) == 1
    finally:
        if owner is not None:
            assert owner.close() is True


def _object(value, name):
    return value if name == 'root' else value[name]


def _replace(value, path, replacement):
    target = value
    for field in path[:-1]:
        target = target[field]
    target[path[-1]] = replacement


def _wire_inputs(value):
    # Escapes permit malformed Unicode to reach the actual decoder/validator.
    # The placeholder confirmation is intentionally not a valid approval: shape
    # rejection must precede binding. Valid binding tests use arguments instead.
    return dict(raw_authority=json.dumps(value, ensure_ascii=False).encode(
                    'utf-8', errors='backslashreplace'),
                confirmed_authority_sha256='0' * 64,
                site_binding={'site_id': 'fixture-site', 'dut_id': 'fixture-dut',
                              'sink_id': 'fixture-sink', 'isolation_ref': 'fixture-isolation'})


