@pytest.mark.parametrize('encoding', ['pretty', 'reversed-keys', 'ascii-escapes'])
def test_equivalent_wire_encodings_use_the_same_canonical_confirmation(
    synthetic, observed_io, encoding,
):
    # A real non-ASCII directory also proves UTF-8 paths are not all rejected.
    child = synthetic.directory / 'synthetic-\u00e9-\ud55c'
    child.mkdir(mode=0o700)
    synthetic.directory = child
    synthetic.value = document(synthetic.raw, child, now_ms=synthetic.clock['wall'])
    inputs = arguments(synthetic.value)
    expected = inputs['confirmed_authority_sha256']
    if encoding == 'pretty':
        wire = json.dumps(synthetic.value, indent=4, ensure_ascii=False).encode('utf-8')
    elif encoding == 'reversed-keys':
        reordered = {key: synthetic.value[key] for key in reversed(sorted(synthetic.value))}
        wire = json.dumps(reordered, separators=(',', ':'), ensure_ascii=False).encode('utf-8')
    else:
        wire = json.dumps(synthetic.value, sort_keys=True, separators=(',', ':'),
                          ensure_ascii=True).encode('utf-8')
    assert wire != inputs['raw_authority']
    assert hashlib.sha256(wire).hexdigest() != expected
    inputs['raw_authority'] = wire
    _accept(synthetic, observed_io, inputs)


def test_pretty_wire_hash_is_not_the_confirmation_hash(synthetic, observed_io):
    inputs = arguments(synthetic.value)
    canonical_confirmation = inputs['confirmed_authority_sha256']
    inputs['raw_authority'] = json.dumps(synthetic.value, indent=2).encode()
    inputs['confirmed_authority_sha256'] = hashlib.sha256(inputs['raw_authority']).hexdigest()
    assert inputs['confirmed_authority_sha256'] != canonical_confirmation
    _refuse(synthetic, observed_io, inputs, 'AUTHORITY_MISMATCH')
    inputs['confirmed_authority_sha256'] = canonical_confirmation
    _accept(synthetic, observed_io, inputs)


