"""Generate AI-only browser Unicode tables from the project's Python 3.12.

Run from the repository: .venv/bin/python web/src/pages/ai-settings/tools/generate_unicode.py
Pass --check to compare all output bytes without writing. No downloads or host data.
"""

import argparse
import json
import stringprep
import sys
import unicodedata
from pathlib import Path

HERE = Path(__file__).resolve().parents[1]
HEADER = "// Generated by tools/generate_unicode.py; Python 3.12 / Unicode 15.0.0.\n"


def require_runtime():
    if sys.version_info[:2] != (3, 12) or unicodedata.unidata_version != "15.0.0":
        raise SystemExit("Use the project's .venv/bin/python (3.12, Unicode 15.0.0)")


def string_table(name, mapping):
    return (
        "// prettier-ignore\n"
        f"export const {name}: Readonly<Record<number, string>> = {{\n"
        + "".join(
            f"  {cp}: {json.dumps(value, ensure_ascii=True)},\n" for cp, value in mapping.items()
        )
        + "};\n"
    )


def ranges_table(name, points):
    ranges = []
    for cp in points:
        if ranges and cp == ranges[-1][1] + 1:
            ranges[-1][1] = cp
        else:
            ranges.append([cp, cp])
    return (
        f"export const {name}: ReadonlyArray<readonly [number, number]> = [\n"
        + "".join(f"  [{start}, {end}],\n" for start, end in ranges)
        + "];\n"
    )


def outputs():
    folds = {}
    decomposed = {}
    combining = {}
    compositions = {}
    properties = {
        name: []
        for name in (
            "TEXT_FORBIDDEN",
            "SPACE",
            "URL_DELIMITERS",
            "IDNA_PROHIBITED",
            "RANDAL",
            "LCAT",
        )
    }
    ucd = unicodedata.ucd_3_2_0
    prohibited = [
        getattr(stringprep, "in_table_" + table)
        for table in ("c12", "c22", "c3", "c4", "c5", "c6", "c7", "c8", "c9")
    ]
    for cp in range(0x110000):
        c = chr(cp)
        if c.casefold() != c:
            folds[cp] = c.casefold()
        if unicodedata.category(c) in {"Cc", "Cf", "Cs"}:
            properties["TEXT_FORBIDDEN"].append(cp)
        if c.isspace():
            properties["SPACE"].append(cp)
        if c not in "/?#@:" and any(d in unicodedata.normalize("NFKC", c) for d in "/?#@:"):
            properties["URL_DELIMITERS"].append(cp)
        # Python's IDNA2003 codec uses Nameprep/B2 and Unicode 3.2 normalization,
        # including AllowUnassigned. Capture the actual 3.12 B2 lowercase here.
        mapped = "" if stringprep.in_table_b1(c) else stringprep.map_table_b2(c)
        value = ucd.normalize("NFKD", mapped)
        if value != c and not 0xAC00 <= cp <= 0xD7A3:
            decomposed[cp] = value
        if cc := ucd.combining(c):
            combining[cp] = cc
        decomposition = ucd.decomposition(c).split()
        if len(decomposition) == 2 and not decomposition[0].startswith("<"):
            pair = "".join(chr(int(p, 16)) for p in decomposition)
            if ucd.normalize("NFC", pair) == c:
                compositions[",".join(str(ord(p)) for p in pair)] = c
        if any(check(c) for check in prohibited):
            properties["IDNA_PROHIBITED"].append(cp)
        if stringprep.in_table_d1(c):
            properties["RANDAL"].append(cp)
        if stringprep.in_table_d2(c):
            properties["LCAT"].append(cp)
    data = (
        HEADER
        + "// Nameprep normalization/prohibition/bidi are Unicode 3.2.0, as in CPython IDNA.\n"
    )
    data += string_table("NAMEPREP_DECOMPOSE", decomposed)
    data += "export const COMBINING: Readonly<Record<number, number>> = {\n"
    data += "".join(f"  {cp}: {cc},\n" for cp, cc in combining.items()) + "};\n"
    data += "export const COMPOSE: Readonly<Record<string, string>> = {\n"
    data += "".join(f"  {json.dumps(pair)}: {json.dumps(c)},\n" for pair, c in compositions.items())
    data += "};\n"
    text = HEADER
    for name, points in properties.items():
        if name in {"TEXT_FORBIDDEN", "SPACE", "URL_DELIMITERS"}:
            text += ranges_table(name, points)
        else:
            data += ranges_table(name, points)
    return {
        "casefold-data.ts": HEADER + string_table("CASE_FOLD", folds),
        "text-data.ts": text,
        "idna-data.ts": data,
    }


def main():
    require_runtime()
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    for filename, content in outputs().items():
        target = HERE / filename
        if args.check:
            if not target.exists() or target.read_bytes() != content.encode():
                raise SystemExit(f"Stale generated data: {target}")
        else:
            target.write_bytes(content.encode())
        print(f"{'checked' if args.check else 'generated'} {filename}")


if __name__ == "__main__":
    main()
